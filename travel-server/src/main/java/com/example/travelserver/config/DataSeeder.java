    private final CityRepository cityRepository;
    private final AttractionRepository attractionRepository;

    public DataSeeder(CityRepository cityRepository, AttractionRepository attractionRepository) {
        this.cityRepository = cityRepository;
        this.attractionRepository = attractionRepository;
    }

    @Override
    public void run(ApplicationArguments args) {
        if (cityRepository.count() > 0) {
            return;
        }

        Map<String, Long> cityIdByName = new HashMap<>();
        for (String line : CITY_DATA.split("\n")) {
            String[] f = line.trim().split("\\|");
            if (f.length < 6) {
                continue;
            }
            City city = new City();
            city.setName(f[0]);
            city.setProvince(f[1]);
            city.setLatitude(Double.parseDouble(f[2]));
            city.setLongitude(Double.parseDouble(f[3]));
            city.setHot("1".equals(f[4]));
            city.setDescription(f[5]);
            cityRepository.save(city);
            cityIdByName.put(city.getName(), city.getId());
        }

        int spotCount = 0;
        for (String line : SPOT_DATA.split("\n")) {
            String[] f = line.trim().split("\\|");
            if (f.length < 10) {
                continue;
            }
            Long cityId = cityIdByName.get(f[0]);
            if (cityId == null) {
                continue;
            }
            Attraction spot = new Attraction();
            spot.setCityId(cityId);
            spot.setName(f[1]);
            spot.setType(f[2]);
            spot.setLatitude(Double.parseDouble(f[3]));
            spot.setLongitude(Double.parseDouble(f[4]));
            spot.setTicket(blankToNull(f[5]));
            spot.setOpenTime(blankToNull(f[6]));
            spot.setPlayTime(blankToNull(f[7]));
            spot.setRating(parseDouble(f[8]));
            spot.setDescription(f[9]);
            attractionRepository.save(spot);
            spotCount++;
        }

        log.info("种子数据初始化完成：{} 个城市，{} 个地点", cityIdByName.size(), spotCount);
    }

    private String blankToNull(String s) {
        return (s == null || s.isBlank() || "—".equals(s.trim())) ? null : s.trim();
    }

    private Double parseDouble(String s) {
        try {
            return Double.parseDouble(s.trim());
        } catch (Exception e) {
            return null;
        }
    }
